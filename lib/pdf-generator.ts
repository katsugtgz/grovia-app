import type { Person } from './types';

export interface PdfTextItem {
  text: string;
  size?: number;
  y: number;
  bold?: boolean;
  x?: number;
}

/**
 * Normalizes text to standard WinAnsi-safe ASCII/Latin-1 characters.
 */
function cleanPdfText(str: string): string {
  return String(str)
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/\u00b7/g, '-')
    .replace(/[^\x20-\x7e]/g, '');
}

function escapePdfText(str: string): string {
  return cleanPdfText(str).replace(/[\\()]/g, (c) => `\\${c}`);
}

export function formatCurrency(num: number): string {
  return `$${Math.round(num).toLocaleString('en-US')}`;
}

/**
 * Pure JS binary %PDF-1.4 generator.
 * Produces valid cross-referenced PDF streams with Helvetica/Helvetica-Bold.
 */
export function generatePdfBlob(items: PdfTextItem[]): Blob {
  const contentStream = items
    .map(
      ({ text, size = 11, y, bold, x = 56 }) =>
        `BT /${bold ? 'F2' : 'F1'} ${size} Tf ${x} ${y} Td (${escapePdfText(text)}) Tj ET`
    )
    .join('\n');

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 4 0 R >>',
    `<< /Length ${contentStream.length} >>\nstream\n${contentStream}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>',
  ];

  let pdfString = '%PDF-1.4\n';
  const offsets = objects.map((obj, i) => {
    const offset = pdfString.length;
    pdfString += `${i + 1} 0 obj\n${obj}\nendobj\n`;
    return offset;
  });

  const xrefOffset = pdfString.length;
  pdfString += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdfString += offsets
    .map((off) => `${String(off).padStart(10, '0')} 00000 n \n`)
    .join('');

  pdfString += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

  return new Blob([pdfString], { type: 'application/pdf' });
}

/**
 * Triggers client-side browser file download from Blob.
 */
export function downloadPdf(blob: Blob, filename: string): void {
  if (typeof window === 'undefined') return;
  const url = URL.createObjectURL(blob);
  const anchor = Object.assign(document.createElement('a'), {
    href: url,
    download: filename,
  });
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/**
 * Builds Employment Contract summary PDF.
 */
export function generateContractPdf(person: Person): Blob {
  const header: PdfTextItem[] = [
    { text: 'Grovia', size: 20, y: 780, bold: true },
    { text: 'Employment contract - summary', size: 13, y: 756 },
  ];

  const pairs: [string, string][] = [
    ['Employee', person.name],
    ['Role', person.role],
    ['Team', person.team],
    ['Based in', person.city],
    ['Start date', person.since || person.hireDate],
    ['Hourly rate', `$${(person.rate ?? 40).toFixed(2)}`],
    ['Overtime', 'Paid at 1.5x after 8 h a day'],
    ['Paid time off', '25 days a year'],
    ['Email', person.email || ''],
  ];

  const bodyItems = pairs.flatMap(([label, val], idx) => [
    { text: label, size: 11, y: 700 - idx * 24 },
    { text: val, size: 11, y: 700 - idx * 24, x: 250, bold: true },
  ]);

  return generatePdfBlob([
    ...header,
    ...bodyItems,
    { text: 'Sample document generated by the Grovia demo.', size: 9, y: 80 },
  ]);
}

/**
 * Builds Monthly Payslip PDF.
 */
export function generatePayslipPdf(
  person: Person,
  timesheet: { worked: number; ot: number; leave: number }
): Blob {
  const header: PdfTextItem[] = [
    { text: 'Grovia', size: 20, y: 780, bold: true },
    { text: 'Payslip - September 2026', size: 13, y: 756 },
  ];

  const rate = person.rate ?? 40;
  const basePay = timesheet.worked * rate;
  const otPremium = timesheet.ot * rate * 0.5;
  const grossPay = basePay + otPremium;
  const leaveDays = Math.round(timesheet.leave / 8);

  const pairs: [string, string][] = [
    ['Employee', person.name],
    ['Role', `${person.role}, ${person.team}`],
    ['Pay period', '1-30 September 2026'],
    ['Hours worked', timesheet.worked.toFixed(1)],
    ['of which overtime', timesheet.ot.toFixed(1)],
    ['Leave days', String(leaveDays)],
    ['Hourly rate', `$${rate.toFixed(2)}`],
    ['Base pay', formatCurrency(basePay)],
    ['Overtime premium', formatCurrency(otPremium)],
    ['Gross pay', formatCurrency(grossPay)],
  ];

  const bodyItems = pairs.flatMap(([label, val], idx) => [
    { text: label, size: 11, y: 700 - idx * 24 },
    { text: val, size: 11, y: 700 - idx * 24, x: 250, bold: true },
  ]);

  return generatePdfBlob([
    ...header,
    ...bodyItems,
    { text: 'Sample document generated by the Grovia demo.', size: 9, y: 80 },
  ]);
}
