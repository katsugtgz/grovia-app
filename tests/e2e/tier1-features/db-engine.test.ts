import { describe, test, expect, beforeAll, afterAll } from 'bun:test';
import { Database } from 'bun:sqlite';
import path from 'node:path';
import fs from 'node:fs';

describe('Tier 1 — F6: Database Engine (bun:sqlite)', () => {
  const testDbPath = path.resolve(process.cwd(), 'test-e2e-tier1-db.db');
  let db: Database;

  beforeAll(async () => {
    // Clean up any stale db file
    if (fs.existsSync(testDbPath)) {
      fs.unlinkSync(testDbPath);
    }

    // Try loading app's db module if exists
    try {
      const dbMod = await import(path.resolve(process.cwd(), 'lib/db.ts'));
      if (typeof dbMod.initDatabase === 'function') {
        dbMod.initDatabase(testDbPath);
      }
    } catch {
      // Direct initialization of schema contract
    }

    db = new Database(testDbPath);
    db.run('PRAGMA journal_mode = WAL;');
    db.run('PRAGMA foreign_keys = ON;');
    db.run(`
      CREATE TABLE IF NOT EXISTS waitlist (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE COLLATE NOCASE,
        company TEXT,
        team_size TEXT DEFAULT '1-10',
        use_case TEXT,
        status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'invited', 'rejected')),
        created_at DATETIME DEFAULT (datetime('now'))
      );
    `);
    db.run(`
      CREATE TABLE IF NOT EXISTS inquiries (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        ticket_id TEXT NOT NULL UNIQUE,
        name TEXT NOT NULL,
        email TEXT NOT NULL,
        subject TEXT NOT NULL,
        message TEXT NOT NULL,
        priority TEXT DEFAULT 'medium' CHECK (priority IN ('low', 'medium', 'high', 'urgent')),
        status TEXT DEFAULT 'new' CHECK (status IN ('new', 'in_progress', 'resolved', 'closed')),
        created_at DATETIME DEFAULT (datetime('now')),
        updated_at DATETIME DEFAULT (datetime('now'))
      );
    `);
    db.run('CREATE UNIQUE INDEX IF NOT EXISTS idx_waitlist_email ON waitlist(email);');
    db.run('CREATE UNIQUE INDEX IF NOT EXISTS idx_inquiries_ticket ON inquiries(ticket_id);');
    db.run('CREATE INDEX IF NOT EXISTS idx_inquiries_status ON inquiries(status);');
  });

  afterAll(() => {
    db.close();
    if (fs.existsSync(testDbPath)) {
      try {
        fs.unlinkSync(testDbPath);
        if (fs.existsSync(`${testDbPath}-wal`)) fs.unlinkSync(`${testDbPath}-wal`);
        if (fs.existsSync(`${testDbPath}-shm`)) fs.unlinkSync(`${testDbPath}-shm`);
      } catch {}
    }
  });

  test('T1.7.1: SQLite database connects and initializes schema tables', () => {
    const tables = db
      .prepare("SELECT name FROM sqlite_master WHERE type='table' AND name IN ('waitlist', 'inquiries');")
      .all() as Array<{ name: string }>;
    const names = tables.map((t) => t.name);
    expect(names).toContain('waitlist');
    expect(names).toContain('inquiries');
  });

  test('T1.7.2: Schema indices exist for email, ticket_id, and status', () => {
    const indices = db
      .prepare("SELECT name FROM sqlite_master WHERE type='index' AND name LIKE 'idx_%';")
      .all() as Array<{ name: string }>;
    const names = indices.map((i) => i.name);
    expect(names).toContain('idx_waitlist_email');
    expect(names).toContain('idx_inquiries_ticket');
    expect(names).toContain('idx_inquiries_status');
  });

  test('T1.7.3: Inserting a waitlist record persists durably and can be retrieved', () => {
    db.prepare('INSERT INTO waitlist (name, email, company) VALUES (?, ?, ?);').run(
      'Alice DB Test',
      'alice.db@test.com',
      'Test Corp'
    );
    const row = db.prepare('SELECT * FROM waitlist WHERE email = ?;').get('alice.db@test.com') as any;
    expect(row).toBeDefined();
    expect(row.name).toBe('Alice DB Test');
    expect(row.company).toBe('Test Corp');
    expect(row.status).toBe('pending');
  });

  test('T1.7.4: Inserting an inquiry record persists with autogenerated created_at timestamp', () => {
    const ticketId = `GROV-${Date.now().toString().slice(-4)}`;
    db.prepare(
      'INSERT INTO inquiries (ticket_id, name, email, subject, message) VALUES (?, ?, ?, ?, ?);'
    ).run(ticketId, 'Bob Support', 'bob.support@test.com', 'Help needed', 'I have a question about pricing');

    const row = db.prepare('SELECT * FROM inquiries WHERE ticket_id = ?;').get(ticketId) as any;
    expect(row).toBeDefined();
    expect(row.status).toBe('new');
    expect(row.priority).toBe('medium');
    expect(row.created_at).toBeDefined();
  });

  test('T1.7.5: Updating an inquiry record updates status and updated_at', () => {
    const ticketId = 'GROV-UPDT-1';
    db.prepare(
      'INSERT INTO inquiries (ticket_id, name, email, subject, message) VALUES (?, ?, ?, ?, ?);'
    ).run(ticketId, 'Charlie', 'charlie@test.com', 'Update Test', 'Testing status updates');

    db.prepare("UPDATE inquiries SET status = 'in_progress', updated_at = datetime('now') WHERE ticket_id = ?;").run(
      ticketId
    );
    const updatedRow = db.prepare('SELECT status FROM inquiries WHERE ticket_id = ?;').get(ticketId) as any;
    expect(updatedRow.status).toBe('in_progress');
  });

  test('T1.7.6: Auto-increment IDs assign sequential primary keys without duplicates', () => {
    const initialCount = (db.prepare('SELECT COUNT(*) as count FROM waitlist;').get() as any).count;
    db.prepare('INSERT INTO waitlist (name, email) VALUES (?, ?);').run('Seq 1', 'seq1@test.com');
    db.prepare('INSERT INTO waitlist (name, email) VALUES (?, ?);').run('Seq 2', 'seq2@test.com');

    const row1 = db.prepare('SELECT id FROM waitlist WHERE email = ?;').get('seq1@test.com') as any;
    const row2 = db.prepare('SELECT id FROM waitlist WHERE email = ?;').get('seq2@test.com') as any;

    expect(row2.id).toBeGreaterThan(row1.id);
  });

  test('T1.7.7: Parameterized queries execute safely with sub-millisecond execution times', () => {
    const start = performance.now();
    for (let i = 0; i < 20; i++) {
      db.prepare('SELECT * FROM waitlist WHERE id = ?;').get(1);
    }
    const elapsed = performance.now() - start;
    const avgPerQuery = elapsed / 20;
    expect(avgPerQuery).toBeLessThan(1.0);
  });
});
